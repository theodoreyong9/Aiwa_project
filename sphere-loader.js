/**
 * The pinned sphere, as { file, source }. author / manifest are 64-hex ids, domain is `contract:<author>:<slug>`;
 * eventsUrl (optional) is where an export of the signed events is published.
 */
export function buildSphere({ author, domain, manifest, slug, title, description, icon, eventsUrl = null, page = PAGE }) {
  if (!HEX.test(author) || !HEX.test(manifest) || !DOMAIN.test(domain) || !SLUG.test(slug)) throw new Error('not a publishable contract identity');
  if (eventsUrl !== null && !/^https:\/\/[^\s'"\\<>]+$/.test(eventsUrl)) throw new Error('the export address must be an https URL');
  const file = `${slug}.sphere.js`;
  const values = {
    __AUTHOR__: author, __DOMAIN__: domain, __MANIFEST__: manifest, __SLUG__: slug, __FILE__: file, __PAGE__: page,
    __EVENTS_URL__: eventsUrl === null ? 'null' : `'${eventsUrl}'`,
    __NAME__: sanitizeMeta(title, 120) || slug,
    __ICON__: sanitizeMeta(icon || '\u{1F537}', 8) || '\u{1F537}',
    __DESC__: sanitizeMeta(description || `${title} — an Aiwa contract, run inside YourMine.`, 120),
  };
  // A function as the replacement: a value holding `$&` or `$1` must be written as it is.
  const source = TEMPLATE.replace(/__[A-Z_]+__/g, (key) => (key in values ? values[key] : key));
  return { file, source };
}
