// sphere-loader.js — the YourMine sphere that runs a PUBLISHED Aiwa contract, and what goes with it.
//
// A sphere must not carry its own copy of a contract: the point of publishing it in Aiwa is that the
// published version is immutable. So the sphere generated here holds only the contract's IDENTITY — who
// published it, its address, and the id of its manifest event (the hash of that exact version) — and is
// pinned to it. At run time it fetches the signed events from wherever they are, checks every signature
// and every hash with aiwa-core's own verifyEvent, and only then runs the code. Same id, same bytes.
//
// Why verifyEvent event by event instead of appending to an EventLog: EventLog.append demands every parent
// of an event to be known, and a manifest's parents include the heads of the publisher's WHOLE log (their
// wallet history). verifyEvent needs none of that: the public key travels in the event, the id is the hash
// of its content, the signature is checked against the key. The manifest names each file event by its id,
// each file event's id is the hash of its content: pinning the manifest id pins every byte.
//
// Where the events come from, in this order: what this device already verified (kept by the hash);
// the public address of an export, if the sphere was given one; the Aiwa page of this device, in a window
// the user allows (bundle-provider.html — a cross-site iframe would only see a partitioned, empty storage).

const PAGE = 'https://theodoreyong9.github.io/Aiwa_project/';

/** text as the inside of a single-quoted JS literal YourMine's merge.js can read: 1 to 120 characters between apostrophes, no $ { } or line break. */
export function sanitizeMeta(text, limit = 120) {
  text = String(text ?? '').replace(/'/g, '\u2019').replace(/[\\$\{\}\u0000-\u001f]/g, ' ').replace(/ {2,}/g, ' ').trim();
  if (text.length <= limit) return text;
  const cut = text.slice(0, limit - 1);
  const words = cut.includes(' ', Math.floor(limit / 2)) ? cut.slice(0, cut.lastIndexOf(' ')) : cut;
  return words.replace(/[ ,;:-]+$/, '') + '\u2026';
}

/** The sphere's name, description and icon, read from the contract's own <title> and <meta> tags (needs a DOM). */
export function contractMeta(html, fallbackName) {
  const doc = new DOMParser().parseFromString(html, 'text/html');
  const meta = (name) => doc.querySelector(`meta[name="${name}"]`)?.getAttribute('content')?.trim() || '';
  const title = sanitizeMeta(doc.querySelector('title')?.textContent || '', 120) || sanitizeMeta(fallbackName, 120);
  return {
    title,
    description: sanitizeMeta(meta('description') || `${title} — an Aiwa contract, run inside YourMine.`, 120),
    icon: sanitizeMeta(meta('aiwa-icon') || '\u{1F537}', 8) || '\u{1F537}',
  };
}

/** The signed events that ARE a published version — its manifest and its files, nothing else (no ancestors, no wallet history). Null when the log does not hold them. */
export async function exportPackage(log, manifestEventId) {
  const manifest = await log.get(manifestEventId);
  if (!manifest || manifest.type !== 'bundle.manifest') return null;
  const files = [];
  for (const id of Object.values(manifest.payload.files ?? {})) {
    const event = await log.get(id);
    if (!event || event.type !== 'bundle.file') return null;
    files.push(event);
  }
  return { manifest, files };
}

/** YourMine's address that opens Build → Apps with a sphere in the code field (the `#aiwa=1;name;code` hand-off of YourMine's build.js; code = deflate-raw, base64url). */
export async function yourMineUrl(fileName, source, base = 'https://yourmine-dapp.web.app/') {
  const packed = await new Response(new Blob([new TextEncoder().encode(source)]).stream().pipeThrough(new CompressionStream('deflate-raw'))).arrayBuffer();
  let binary = '';
  for (const byte of new Uint8Array(packed)) binary += String.fromCharCode(byte);
  const payload = btoa(binary).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
  return `${base}#aiwa=1;${fileName};${payload}`;
}

