  if(m.type !== 'bundle.manifest' || m.author !== PIN.author || m.domain !== PIN.domain) throw new Error('wrong publisher or address');
  if(!(await core.verifyEvent(m)).valid) throw new Error('the manifest is not authentic');
  const files = {};
